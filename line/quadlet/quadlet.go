// Package quadlet renders the systemd units of one line on a shared host:
// podman Quadlet .container, .network and .volume files plus a resource slice.
// See design-docs/multi-line-host.md.
package quadlet

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

// Spec is everything that differs between two lines on one host.
type Spec struct {
	Name        string // line name; becomes part of unit, network and volume names
	Dir         string // absolute host path of the line directory, mounted at the same path
	Port        int    // station API port, from the line's line.toml
	ProjectPath string // absolute host path of the beads workspace
	Image       string // image holding the sweatshop binary; its entrypoint must be unset
	CPUQuota    string // systemd CPUQuota=, e.g. "200%"
	MemoryMax   string // systemd MemoryMax=, e.g. "8G"
	// MirrorCredDir is the host directory holding the line's mirror deploy key
	// and known_hosts (see mirror.SSHAuth). Empty means the line has no
	// mirror service. Only that service mounts it, never a station.
	MirrorCredDir string
}

// File is one unit file to write.
type File struct {
	Name    string // file name, e.g. sweatshop-x-serve.container
	Content string
	Slice   bool // a plain systemd unit; Quadlet does not read it
}

var lineName = regexp.MustCompile(`^[a-z0-9]+(-[a-z0-9]+)*$`)

// podmanSocket is the rootless podman API socket; %t is the systemd runtime dir.
const podmanSocket = "%t/podman/podman.sock:/run/podman/podman.sock"

func (s Spec) validate() error {
	switch {
	case !lineName.MatchString(s.Name):
		return fmt.Errorf("quadlet: bad line name %q (want lowercase letters, digits and single dashes)", s.Name)
	case !filepath.IsAbs(s.Dir) || !filepath.IsAbs(s.ProjectPath):
		return fmt.Errorf("quadlet: line dir %q and project path %q must be absolute", s.Dir, s.ProjectPath)
	case s.Port < 1 || s.Port > 65535:
		return fmt.Errorf("quadlet: bad port %d", s.Port)
	case s.Image == "" || s.CPUQuota == "" || s.MemoryMax == "":
		return fmt.Errorf("quadlet: image, CPU quota and memory max are required")
	}
	// A newline would add a unit key; % in a path would start a systemd specifier.
	if s.MirrorCredDir != "" && !filepath.IsAbs(s.MirrorCredDir) {
		return fmt.Errorf("quadlet: mirror credential dir %q must be absolute", s.MirrorCredDir)
	}
	for _, v := range []string{s.Dir, s.ProjectPath, s.Image, s.MirrorCredDir} {
		if strings.ContainsAny(v, "\n\r%") {
			return fmt.Errorf("quadlet: unsafe value %q", v)
		}
	}
	for _, v := range []string{s.CPUQuota, s.MemoryMax} {
		if strings.ContainsAny(v, "\n\r") {
			return fmt.Errorf("quadlet: unsafe value %q", v)
		}
	}
	return nil
}

// Render returns the line's unit files: network, state volume, slice and the
// serve, heijunka, andon and kaizen containers, plus the mirror container when
// MirrorCredDir is set.
func Render(s Spec) ([]File, error) {
	if err := s.validate(); err != nil {
		return nil, err
	}
	n := "sweatshop-" + s.Name
	port := strconv.Itoa(s.Port)
	stations := filepath.Join(s.Dir, "stations")

	container := func(role, desc, command, station string, extra ...string) File {
		lines := []string{
			"# Generated by `sweatshop line install --name " + s.Name + "`; edit that command's flags, not this file.",
			"[Unit]",
			"Description=sweatshop " + role + " (line " + s.Name + "): " + desc,
			"",
			"[Container]",
			"Image=" + s.Image,
			"ContainerName=" + n + "-" + role,
			"Network=" + n + ".network",
			"Volume=" + n + "-state.volume:" + s.Dir,
			"Exec=" + command,
		}
		if station != "" {
			lines = append(lines,
				"EnvironmentFile="+filepath.Join(stations, station, "env"),
				"Environment=SWEATSHOP_LINE_URL=http://"+n+"-serve:"+port)
		}
		lines = append(lines, extra...)
		lines = append(lines,
			"",
			"[Service]",
			"Slice="+n+".slice",
			"Restart=always",
			"RestartSec=10",
			"",
			"[Install]",
			"WantedBy=default.target",
			"")
		return File{Name: n + "-" + role + ".container", Content: strings.Join(lines, "\n")}
	}
	engine := []string{
		"Volume=" + podmanSocket,
		"Environment=CONTAINER_HOST=unix:///run/podman/podman.sock",
		"SecurityLabelDisable=true",
	}
	project := "Volume=" + s.ProjectPath + ":" + s.ProjectPath

	files := []File{
		{Name: n + ".network", Content: "[Network]\nNetworkName=" + n + "\n"},
		{Name: n + "-state.volume", Content: "# Binds the line directory so line.db and the remote survive container replacement.\n" +
			"[Volume]\nVolumeName=" + n + "-state\nType=none\nDevice=" + s.Dir + "\nOptions=bind\n"},
		{Name: n + ".slice", Slice: true, Content: "[Unit]\nDescription=sweatshop line " + s.Name + " resources\n\n" +
			"[Slice]\nCPUQuota=" + s.CPUQuota + "\nMemoryMax=" + s.MemoryMax + "\n"},
		container("serve", "station API",
			"sweatshop line serve --dir "+s.Dir+" --addr 0.0.0.0:"+port+" --unsafe-listen --beads "+s.ProjectPath, "",
			append([]string{"PublishPort=127.0.0.1:" + port + ":" + port, project}, engine...)...),
		container("heijunka", "levels agents and WIP limit",
			"sweatshop line heijunka --beads "+s.ProjectPath+" --interval 5m", "heijunka-1", project),
		container("andon", "attests each new master",
			"sweatshop line andon --beads "+s.ProjectPath, "andon-1", project),
		container("kaizen", "one small improvement per interval",
			"sweatshop line kaizen --dir "+s.Dir+" --station kaizen-1 --interval 24h", "kaizen-1", engine...),
	}
	if s.MirrorCredDir != "" {
		files = append(files, container("mirror", "publishes master, tags and attestations to the constitution's storage mirrors",
			"sweatshop line mirror --dir "+s.Dir+" --creds "+s.MirrorCredDir+" --interval 1m", "",
			"Volume="+s.MirrorCredDir+":"+s.MirrorCredDir+":ro"))
	}
	return files, nil
}

// Install writes Render's files: Quadlet files into quadletDir and the slice
// into sliceDir. It overwrites existing files and runs nothing; the caller
// reloads systemd.
func Install(s Spec, quadletDir, sliceDir string) ([]string, error) {
	files, err := Render(s)
	if err != nil {
		return nil, err
	}
	var written []string
	for _, f := range files {
		dir := quadletDir
		if f.Slice {
			dir = sliceDir
		}
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return nil, err
		}
		path := filepath.Join(dir, f.Name)
		if err := os.WriteFile(path, []byte(f.Content), 0o644); err != nil {
			return nil, err
		}
		written = append(written, path)
	}
	return written, nil
}
