// Package quadlet renders the systemd units of one line on a shared host:
// podman Quadlet .container, .network and .volume files plus a resource slice.
// See design-docs/multi-line-host.md.
package quadlet

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	"github.com/Fewbytes/sweatshop/line/secret"
)

// Spec is everything that differs between two lines on one host.
type Spec struct {
	Name        string // line name; becomes part of unit, network and volume names
	Dir         string // absolute host path of the line directory, mounted at the same path
	Port        int    // station API port, from the line's line.toml
	URL         string // station API as station containers see it, from line.toml; empty means http://sweatshop-NAME-serve:PORT
	ProjectPath string // absolute host path of the beads workspace
	Image       string // image holding the sweatshop binary; its entrypoint must be unset
	CPUQuota    string // systemd CPUQuota=, e.g. "200%"
	MemoryMax   string // systemd MemoryMax=, e.g. "8G"
	// MirrorCredDir is the host directory holding the line's mirror deploy key
	// and known_hosts (see mirror.SSHAuth). Empty means the line has no
	// mirror service. Only that service mounts it, never a station.
	MirrorCredDir string
	// Makers names the stations of role maker; each gets a unit running
	// MakerImage with podman secrets for its token and the model credential.
	Makers     []string
	MakerImage string // image of the maker loop (station/Dockerfile maker target)
}

// File is one unit file to write.
type File struct {
	Name    string // file name, e.g. sweatshop-x-serve.container
	Content string
	Slice   bool // a plain systemd unit; Quadlet does not read it
}

var lineName = regexp.MustCompile(`^[a-z0-9]+(-[a-z0-9]+)*$`)

// podmanSocket is the rootless podman API socket; %t is the systemd runtime dir.
const podmanSocket = "%t/podman/podman.sock:/run/podman/podman.sock"

func (s Spec) validate() error {
	switch {
	case !lineName.MatchString(s.Name):
		return fmt.Errorf("quadlet: bad line name %q (want lowercase letters, digits and single dashes)", s.Name)
	case !filepath.IsAbs(s.Dir) || !filepath.IsAbs(s.ProjectPath):
		return fmt.Errorf("quadlet: line dir %q and project path %q must be absolute", s.Dir, s.ProjectPath)
	case s.Port < 1 || s.Port > 65535:
		return fmt.Errorf("quadlet: bad port %d", s.Port)
	case s.Image == "" || s.CPUQuota == "" || s.MemoryMax == "":
		return fmt.Errorf("quadlet: image, CPU quota and memory max are required")
	}
	if len(s.Makers) > 0 && s.MakerImage == "" {
		return fmt.Errorf("quadlet: maker image is required when the line has makers")
	}
	for _, m := range s.Makers {
		if !lineName.MatchString(m) {
			return fmt.Errorf("quadlet: bad maker station name %q", m)
		}
	}
	// A newline would add a unit key; % in a path would start a systemd specifier.
	if s.MirrorCredDir != "" && !filepath.IsAbs(s.MirrorCredDir) {
		return fmt.Errorf("quadlet: mirror credential dir %q must be absolute", s.MirrorCredDir)
	}
	for _, v := range []string{s.Dir, s.ProjectPath, s.Image, s.MakerImage, s.MirrorCredDir} {
		if strings.ContainsAny(v, "\n\r%") {
			return fmt.Errorf("quadlet: unsafe value %q", v)
		}
	}
	for _, v := range []string{s.CPUQuota, s.MemoryMax} {
		if strings.ContainsAny(v, "\n\r") {
			return fmt.Errorf("quadlet: unsafe value %q", v)
		}
	}
	return nil
}

// Render returns the line's unit files: network, state volume, slice and the
// serve, heijunka, andon and kaizen containers, plus the mirror container when
// MirrorCredDir is set, plus one maker container per entry of Makers.
func Render(s Spec) ([]File, error) {
	if err := s.validate(); err != nil {
		return nil, err
	}
	n := "sweatshop-" + s.Name
	port := strconv.Itoa(s.Port)
	stations := filepath.Join(s.Dir, "stations")
	stationURL := s.URL
	if stationURL == "" {
		stationURL = "http://" + n + "-serve:" + port
	}

	generated := "# Generated by `sweatshop line install --name " + s.Name + "`; edit that command's flags, not this file."
	container := func(role, desc, command, station string, extra ...string) File {
		lines := []string{
			generated,
			"[Unit]",
			"Description=sweatshop " + role + " (line " + s.Name + "): " + desc,
			"",
			"[Container]",
			"Image=" + s.Image,
			"ContainerName=" + n + "-" + role,
			"Network=" + n + ".network",
			"Volume=" + n + "-state.volume:" + s.Dir,
			"Exec=" + command,
		}
		if station != "" {
			lines = append(lines,
				"EnvironmentFile="+filepath.Join(stations, station, "env"),
				"Environment=SWEATSHOP_LINE_URL="+stationURL)
		}
		lines = append(lines, extra...)
		lines = append(lines,
			"",
			"[Service]",
			"Slice="+n+".slice",
			"Restart=always",
			"RestartSec=10",
			"",
			"[Install]",
			"WantedBy=default.target",
			"")
		return File{Name: n + "-" + role + ".container", Content: strings.Join(lines, "\n")}
	}
	engine := []string{
		"Volume=" + podmanSocket,
		"Environment=CONTAINER_HOST=unix:///run/podman/podman.sock",
		"SecurityLabelDisable=true",
	}
	project := "Volume=" + s.ProjectPath + ":" + s.ProjectPath

	files := []File{
		{Name: n + ".network", Content: "[Network]\nNetworkName=" + n + "\n"},
		{Name: n + "-state.volume", Content: "# Binds the line directory so line.db and the remote survive container replacement.\n" +
			"[Volume]\nVolumeName=" + n + "-state\nType=none\nDevice=" + s.Dir + "\nOptions=bind\n"},
		{Name: n + ".slice", Slice: true, Content: "[Unit]\nDescription=sweatshop line " + s.Name + " resources\n\n" +
			"[Slice]\nCPUQuota=" + s.CPUQuota + "\nMemoryMax=" + s.MemoryMax + "\n"},
		container("serve", "station API",
			"sweatshop line serve --dir "+s.Dir+" --addr 0.0.0.0:"+port+" --unsafe-listen --beads "+s.ProjectPath, "",
			append([]string{"PublishPort=127.0.0.1:" + port + ":" + port, project}, engine...)...),
		container("heijunka", "levels agents and WIP limit",
			"sweatshop line heijunka --beads "+s.ProjectPath+" --interval 5m", "heijunka-1", project),
		container("andon", "attests each new master",
			"sweatshop line andon --beads "+s.ProjectPath, "andon-1", project),
		container("kaizen", "one small improvement per interval",
			"sweatshop line kaizen --dir "+s.Dir+" --station kaizen-1 --interval 24h", "kaizen-1", engine...),
	}
	if s.MirrorCredDir != "" {
		files = append(files, container("mirror", "publishes master, tags and attestations to the constitution's storage mirrors",
			"sweatshop line mirror --dir "+s.Dir+" --creds "+s.MirrorCredDir+" --interval 1m", "",
			"Volume="+s.MirrorCredDir+":"+s.MirrorCredDir+":ro"))
	}
	for _, m := range s.Makers {
		files = append(files, File{Name: n + "-" + m + ".container", Content: strings.Join([]string{
			generated,
			"[Unit]",
			"Description=sweatshop maker " + m + " (line " + s.Name + ")",
			"",
			"[Container]",
			"Image=" + s.MakerImage,
			"ContainerName=" + n + "-" + m,
			"Network=" + n + ".network",
			"Secret=" + TokenSecretName(s.Name, m) + ",type=env,target=SWEATSHOP_LINE_TOKEN",
			"Secret=" + ModelSecretName(s.Name) + ",type=env,target=CLAUDE_CODE_OAUTH_TOKEN",
			"Environment=SWEATSHOP_LINE_URL=" + stationURL,
			"Environment=CONTAINER_HOST=unix:///run/podman/podman.sock",
			"Volume=" + podmanSocket,
			"Volume=" + s.Dir + ":" + s.Dir + ":ro",
			"SecurityLabelDisable=true",
			"Exec=--dir " + s.Dir + " --station " + m,
			"",
			"[Service]",
			"Slice=" + n + ".slice",
			"Restart=always",
			"RestartSec=10",
			"",
			"[Install]",
			"WantedBy=default.target",
			""}, "\n")})
	}
	return files, nil
}

// TokenSecretName is the podman secret holding a maker station's line token.
func TokenSecretName(line, station string) string {
	return "sweatshop-" + line + "-" + station + "-token"
}

// ModelSecretName is the podman secret holding the line's model credential.
func ModelSecretName(line string) string { return "sweatshop-" + line + "-model-cred" }

// SecretCreator stores value as the podman secret name, replacing any older one.
type SecretCreator func(name, value string) error

// CreateMakerSecrets creates the podman secrets the maker units name: each
// maker's token from stations/<name>/token and the model credential from src.
// It returns the secret names created. Errors name secrets and stations, never
// values.
func CreateMakerSecrets(s Spec, src secret.Source, create SecretCreator) ([]string, error) {
	if len(s.Makers) == 0 {
		return nil, nil
	}
	model, err := src.Read(secret.ModelCred)
	if err != nil {
		return nil, fmt.Errorf("quadlet: model credential: %w", err)
	}
	var created []string
	put := func(name, value string) error {
		if err := create(name, value); err != nil {
			return fmt.Errorf("quadlet: create podman secret %s: %w", name, err)
		}
		created = append(created, name)
		return nil
	}
	if err := put(ModelSecretName(s.Name), model); err != nil {
		return created, err
	}
	for _, m := range s.Makers {
		token, err := os.ReadFile(filepath.Join(s.Dir, "stations", m, "token"))
		if err != nil {
			return created, fmt.Errorf("quadlet: station %s token: %w", m, err)
		}
		if err := put(TokenSecretName(s.Name, m), strings.TrimSpace(string(token))); err != nil {
			return created, err
		}
	}
	return created, nil
}

// Install writes Render's files: Quadlet files into quadletDir and the slice
// into sliceDir. It overwrites existing files and runs nothing; the caller
// reloads systemd.
func Install(s Spec, quadletDir, sliceDir string) ([]string, error) {
	files, err := Render(s)
	if err != nil {
		return nil, err
	}
	var written []string
	for _, f := range files {
		dir := quadletDir
		if f.Slice {
			dir = sliceDir
		}
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return nil, err
		}
		path := filepath.Join(dir, f.Name)
		if err := os.WriteFile(path, []byte(f.Content), 0o644); err != nil {
			return nil, err
		}
		written = append(written, path)
	}
	return written, nil
}

// envStation is a station whose unit reads EnvironmentFile=<dir>/stations/<name>/env.
type envStation struct {
	name       string
	needsModel bool // also gets CLAUDE_CODE_OAUTH_TOKEN, which the station passes on to its containers
}

// envStations lists every station that Render gives an EnvironmentFile.
var envStations = []envStation{{"heijunka-1", false}, {"andon-1", false}, {"kaizen-1", true}}

// WriteEnvFiles writes the env file (mode 0600) of each station whose unit
// reads one: SWEATSHOP_LINE_TOKEN from stations/<name>/token and, for kaizen,
// CLAUDE_CODE_OAUTH_TOKEN from the model credential in src. An existing file
// is kept unless rewrite is set. It returns the paths written. Errors name
// files and stations, never values.
func WriteEnvFiles(s Spec, src secret.Source, rewrite bool) ([]string, error) {
	var written []string
	for _, st := range envStations {
		stationDir := filepath.Join(s.Dir, "stations", st.name)
		path := filepath.Join(stationDir, "env")
		if _, err := os.Stat(path); err == nil && !rewrite {
			continue
		}
		token, err := os.ReadFile(filepath.Join(stationDir, "token"))
		if err != nil {
			return written, fmt.Errorf("quadlet: station %s token: %w (add the station with `line station add`)", st.name, err)
		}
		content := "SWEATSHOP_LINE_TOKEN=" + strings.TrimSpace(string(token)) + "\n"
		if st.needsModel {
			model, err := src.Read(secret.ModelCred)
			if err != nil {
				return written, fmt.Errorf("quadlet: station %s model credential: %w", st.name, err)
			}
			content += "CLAUDE_CODE_OAUTH_TOKEN=" + model + "\n"
		}
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			return written, err
		}
		if err := os.Chmod(path, 0o600); err != nil {
			return written, err
		}
		written = append(written, path)
	}
	return written, nil
}
